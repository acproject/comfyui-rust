//! UI localization — English (default) and Chinese.
//!
//! [`tr`] returns the Chinese translation for a key when the UI language is
//! Chinese, otherwise it returns the key unchanged — every key is the exact
//! English source string, so English output is identical to the original code.
//! [`tf`] additionally substitutes positional `{}` placeholders in the
//! (translated) template, so multi-argument strings need a single entry.

use std::fmt;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Zh,
}

impl Lang {
    pub fn from_str(s: &str) -> Lang {
        let n = s.trim().to_lowercase();
        if n == "zh" || n == "zh-cn" || n == "cn" || n == "zh-hans" || n == "zh-hans-cn" || n == "中文" {
            Lang::Zh
        } else {
            Lang::En
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Zh => "zh",
        }
    }

    pub fn toggle(&self) -> Lang {
        match self {
            Lang::En => Lang::Zh,
            Lang::Zh => Lang::En,
        }
    }
}

