/// Translate a template containing positional `{}` placeholders and substitute
/// `args` in order. For English it mirrors `format!`.
pub fn tf(lang: Lang, key: &str, args: &[&dyn fmt::Display]) -> String {
    let tpl = tr(lang, key);
    let mut out = String::with_capacity(tpl.len() + 32);
    let mut args = args.iter();
    for part in tpl.split("{}") {
        out.push_str(part);
        if let Some(arg) = args.next() {
            out.push_str(&arg.to_string());
        }
    }
    out
}
